/* Maximum number of plies in the board database.
** This just needs to be some large value that we will never reach. 
** This is used for storing per-ply statistics, which is a small
** structure.
*/
#define MAX_BRD_PLIES 100

/* Maximum number of workload files for deep search.
*/
#define MAX_SEARCH_WORKLOADS 10'000

/* In order to improve performance for the "mcperft aggregate" command
** enable the 4-byte deep search counter mode.
** The result files use 8 bytes to hold the deep search number of moves, however
** since the deep search is typically 5 or fewer plies deep, only 4 byte counter
** is needed in most use cases. The 4-byte counters require less file space and
** DRAM storage, which makes move aggregation faster. 
**
** The "mcperft aggregate" command prints an error message and aborts if any
** of the result files contain a counter that doesn't fit into 4 bytes. If this 
** happens then modify the code to NOT enable the 4-byte counters and re-run the
** "mcperft aggregate" command.
**
** Note that the USE_4_BYTE_COUNTERS doesn't affect the "mcperft count" command. 
** The result files generated by "mcperft count" always use 8-byte integers to 
** hold the number of moves for each position.
*/
// #undef USE_4_BYTE_COUNTERS
#define USE_4_BYTE_COUNTERS
#ifdef USE_4_BYTE_COUNTERS
typedef unsigned int deepSearchCounter_t;
#else
typedef unsigned long long deepSearchCounter_t;
#endif

/* The position database is mapped to a file. 
** These are the file names for various databases.
*/
#define DIR_NAME "board-db"
